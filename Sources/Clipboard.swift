import AppKit

enum ClipboardClear: Int, CaseIterable, Identifiable {
    case never = 0, thirtySeconds = 30, oneMinute = 60, twoMinutes = 120, fiveMinutes = 300
    var id: Int { rawValue }
    var label: String {
        switch self {
        case .never: return "Never"
        case .thirtySeconds: return "After 30 seconds"
        case .oneMinute: return "After 1 minute"
        case .twoMinutes: return "After 2 minutes"
        case .fiveMinutes: return "After 5 minutes"
        }
    }
}

/// Copies note text to the clipboard and cleans up after it.
/// Only ever wipes the clipboard automatically if it still holds what NotchPad put there,
/// so something you copied from another app afterwards is never touched.
final class ClipboardGuard {
    static let shared = ClipboardGuard()
    private let pb = NSPasteboard.general
    /// Clipboard change count right after our last copy; nil when the clipboard isn't ours.
    private var ourChangeCount: Int?
    private var clearWork: DispatchWorkItem?

    /// True while the clipboard still holds text copied from NotchPad.
    var holdsOurCopy: Bool { ourChangeCount != nil && ourChangeCount == pb.changeCount }

    func copy(_ text: String) {
        let s = Settings.shared
        if s.clipboardThisMacOnly {
            // Keeps it off Universal Clipboard (your iPhone, iPad and other Macs).
            pb.prepareForNewContents(with: .currentHostOnly)
        } else {
            pb.clearContents()
        }
        pb.setString(text, forType: .string)
        if s.clipboardHideFromHistory {
            // Widely-used markers that ask clipboard history apps (Maccy, Raycast, Paste, Alfred...) not to save it.
            pb.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
            pb.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
            pb.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        }
        ourChangeCount = pb.changeCount
        scheduleClear(after: s.clipboardClear)
    }

    private func scheduleClear(after rule: ClipboardClear) {
        clearWork?.cancel()
        clearWork = nil
        guard rule != .never else { return }
        let work = DispatchWorkItem { [weak self] in self?.clearIfOurs() }
        clearWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + .seconds(rule.rawValue), execute: work)
    }

    /// Wipes the clipboard only if it still holds NotchPad's copy.
    func clearIfOurs() {
        clearWork?.cancel()
        clearWork = nil
        if holdsOurCopy { pb.clearContents() }
        ourChangeCount = nil
    }

    /// Wipes whatever is on the clipboard right now, from any app.
    func clearNow() {
        clearWork?.cancel()
        clearWork = nil
        pb.clearContents()
        ourChangeCount = nil
    }
}
